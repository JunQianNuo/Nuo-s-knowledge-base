#!/usr/bin/env python3
"""Build Chapter 8 thermodynamics exercise files with embedded images."""

import os
import shutil
import glob

SRC_IMAGES = r"D:\知识库\课程\大学物理\课件\MD\images"
OUT_DIR = r"D:\知识库\课程\大学物理\习题库\08-热力学基础"
OUT_IMAGES = os.path.join(OUT_DIR, "images")

# Delete old exercise files (keep README.md and images/)
print("=== Cleaning old exercise files ===")
for f in glob.glob(os.path.join(OUT_DIR, "习题8-*.md")):
    os.remove(f)
    print(f"  Deleted: {os.path.basename(f)}")

os.makedirs(OUT_IMAGES, exist_ok=True)
# Also remove old images in output
for f in glob.glob(os.path.join(OUT_IMAGES, "*")):
    os.remove(f)
    print(f"  Deleted old image: {os.path.basename(f)}")

def copy_images(img_names):
    """Copy images from source to output images dir, return wiki-image strings."""
    lines = []
    for name in img_names:
        src = os.path.join(SRC_IMAGES, name)
        dst = os.path.join(OUT_IMAGES, name)
        if os.path.exists(src):
            shutil.copy2(src, dst)
            lines.append("![[images/" + name + "]]")
        else:
            print("  WARNING: Image not found: " + name)
    return "\n\n".join(lines)

def write_exercise(filename, frontmatter_title, topics_list, body_template, img_names):
    """Write an exercise .md file. Handles image insertion."""
    imgs_str = copy_images(img_names)
    body = body_template.replace("__IMAGES__", imgs_str)

    topics_yaml = "\n".join("  - " + t for t in topics_list)
    content = (
        "---\n"
        "title: " + frontmatter_title + "\n"
        "subject: 大学物理\n"
        "chapter: 8\n"
        "section: 热力学基础\n"
        "source: 大学物理II-热学-热力学.pdf\n"
        "status: mineru解析\n"
        "type: 习题\n"
        "topics:\n"
        + topics_yaml + "\n"
        "---\n\n"
        + body + "\n"
    )
    path = os.path.join(OUT_DIR, filename)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    print("  Created: " + filename)


