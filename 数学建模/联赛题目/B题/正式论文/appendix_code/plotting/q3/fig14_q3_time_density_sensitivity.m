function root = projectRoot()

p = fileparts(mfilename('fullpath'));

for k = 1:8

    target = fullfile(p, ...
        'source_code','q3','outputs', ...
        'q3-summary.json');

    if isfile(target)
        root = p;
        return;
    end

    parent = fileparts(p);

    if strcmp(parent,p)
        break;
    end

    p = parent;
end

error('无法自动定位支撑材料根目录。');

end