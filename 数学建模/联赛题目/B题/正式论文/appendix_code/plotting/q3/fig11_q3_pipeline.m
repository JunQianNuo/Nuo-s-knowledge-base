clear; clc;

root = projectRoot();
outDir = fullfile(root, 'source_code', 'q3', 'outputs');

A = jsondecode(fileread(fullfile( ...
    outDir, 'formal_stage_a_summary.json')));

B = jsondecode(fileread(fullfile( ...
    outDir, 'formal_stage_b_summary.json')));

C = jsondecode(fileread(fullfile( ...
    outDir, 'q3-summary.json')));

%% 一致性检查
assert(A.mandatory_served == A.mandatory_total);
assert(B.mandatory_served == A.mandatory_total);
assert(B.B0 == A.T_air);
assert(C.parent_B0 == A.T_air);
assert(C.fixed_temporary_served == B.temporary_served);

assert(A.validation.independent);
assert(B.validation.independent);
assert(C.validation.independent);

tempRate = 100 * B.temporary_served / B.temporary_total;

restrictedDiff = ...
    100 * (A.T_air - A.restricted_pool_bound) / A.T_air;

%% 字体
set(groot, ...
    'defaultAxesFontName', 'Times New Roman', ...
    'defaultTextFontName', 'Times New Roman');

figure('Color', 'w', ...
    'Position', [100 160 1180 480]);

ax = axes('Position', [0.035 0.08 0.93 0.88]);

hold(ax, 'on');
axis(ax, [0 1 0 1]);
axis(ax, 'off');

Cmap = lines(3);

%% Stage A
metricsA = {
    sprintf('Mandatory = %d / %d', ...
        A.mandatory_served, A.mandatory_total)
    sprintf('T_{air} = %d min', A.T_air)
    sprintf('Flights = %d', A.selected_flights)
    sprintf('Aircraft = %d / 24', A.aircraft_used)
    sprintf('Restricted-pool difference = %.1f%%', ...
        restrictedDiff)
    sprintf('Status = %s', A.status)
    };

drawStage(ax, ...
    0.020, 0.285, Cmap(1,:), ...
    'Stage A', ...
    '非临时任务基准', ...
    metricsA);

%% Stage B
metricsB = {
    sprintf('Mandatory = %d / %d', ...
        B.mandatory_served, A.mandatory_total)
    sprintf('Temporary = %d / %d', ...
        B.temporary_served, B.temporary_total)
    sprintf('Acceptance = %.3f%%', tempRate)
    sprintf('T_{air} = %d min', B.T_air)
    sprintf('B_0 = %d min', B.B0)
    sprintf('Zero-option groups = %d', ...
        B.zero_option_temporary_groups)
    };

drawStage(ax, ...
    0.3575, 0.285, Cmap(2,:), ...
    'Stage B', ...
    '临时任务接纳', ...
    metricsB);

%% Stage C
metricsC = {
    sprintf('T_{air} = %d min', C.T_air)
    sprintf('T_{pax} = %d person-min', C.T_pax)
    sprintf('Fuel = %.1f kg', C.fuel)
    sprintf('Flights = %d', C.flights)
    sprintf('Utilization = %.2f%%', ...
        100*C.utilization)
    sprintf('Aircraft = %d / 24', C.aircraft_used)
    };

drawStage(ax, ...
    0.695, 0.285, Cmap(3,:), ...
    'Stage C', ...
    '词典序细化', ...
    metricsC);

%% 流程箭头
quiver(ax, ...
    0.312, 0.50, 0.036, 0, 0, ...
    'LineWidth', 1.6, ...
    'MaxHeadSize', 1.2, ...
    'Color', [0.25 0.25 0.25]);

quiver(ax, ...
    0.649, 0.50, 0.036, 0, 0, ...
    'LineWidth', 1.6, ...
    'MaxHeadSize', 1.2, ...
    'Color', [0.25 0.25 0.25]);

text(ax, 0.330, 0.565, ...
    sprintf('B_0 = %d', A.T_air), ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10);

text(ax, 0.668, 0.565, ...
    sprintf('Temporary = %d', ...
    B.temporary_served), ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10);

%% 验证说明
text(ax, 0.5, 0.055, ...
    'Independent validator: PASS    |    Solver = delivery: PASS', ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10.5);


function drawStage(ax, x0, w, edgeColor, ...
    stageName, chineseName, metrics)

rectangle(ax, ...
    'Position', [x0 0.16 w 0.70], ...
    'Curvature', 0.045, ...
    'FaceColor', [0.985 0.985 0.985], ...
    'EdgeColor', edgeColor, ...
    'LineWidth', 1.8);

text(ax, ...
    x0+w/2, 0.790, stageName, ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 15, ...
    'FontWeight', 'bold');

text(ax, ...
    x0+w/2, 0.720, chineseName, ...
    'HorizontalAlignment', 'center', ...
    'FontName', 'SimSun', ...
    'FontSize', 13);

ys = linspace(0.615, 0.285, numel(metrics));

for i = 1:numel(metrics)

    text(ax, ...
        x0+w/2, ys(i), metrics{i}, ...
        'HorizontalAlignment', 'center', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 10.2, ...
        'Interpreter', 'tex');

end

end


function root = projectRoot()

p = fileparts(mfilename('fullpath'));

for k = 1:8

    target = fullfile(p, ...
        'source_code', 'q3', 'outputs', ...
        'q3-summary.json');

    if isfile(target)
        root = p;
        return;
    end

    parent = fileparts(p);

    if strcmp(parent, p)
        break;
    end

    p = parent;
end

error('无法自动定位支撑材料根目录。');

end