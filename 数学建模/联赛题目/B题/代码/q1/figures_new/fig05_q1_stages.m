clear; clc;

root = projectRoot();

summaryFile = fullfile(root, '代码', 'q1', ...
    'outputs', 'q1-summary.json');

if ~isfile(summaryFile)
    error('找不到文件：%s', summaryFile);
end

S = jsondecode(fileread(summaryFile));
stages = S.stages;

set(groot, ...
    'defaultAxesFontName', 'Times New Roman', ...
    'defaultTextFontName', 'Times New Roman');

stageNames = { ...
    'T_{air}', ...
    'T_{pax}', ...
    'Fuel', ...
    'Flights', ...
    'Utilization'};

n = numel(stages);

gap = nan(n,1);
time = zeros(n,1);

for i = 1:n
    time(i) = stages(i).wall_time;

    if i <= 4
        gap(i) = 100 * stages(i).gap;
    end
end

figure('Color', 'w', ...
    'Position', [180 70 920 720]);

tl = tiledlayout(2, 1, ...
    'TileSpacing', 'compact', ...
    'Padding', 'compact');

%% (a) 求解器相对差距
ax1 = nexttile;
hold(ax1, 'on');

for i = 1:4

    plot(ax1, ...
        [0 gap(i)], [i i], '-', ...
        'LineWidth', 1.6);

    scatter(ax1, ...
        gap(i), i, 60, ...
        'filled');

    text(ax1, ...
        gap(i), i, ...
        sprintf('  %.2f%%', gap(i)), ...
        'VerticalAlignment', 'middle', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 10);
end

%% Stage 5 为分式目标，不直接给普通 gap
scatter(ax1, 0, 5, 55, ...
    'o', ...
    'LineWidth', 1.4);

text(ax1, 0, 5, ...
    '  N/A (Dinkelbach)', ...
    'VerticalAlignment', 'middle', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10);

yticks(ax1, 1:5);
yticklabels(ax1, stageNames);

ylim(ax1, [0.5 5.5]);

xlabel(ax1, ...
    'Relative incumbent-bound difference / %', ...
    'FontName', 'Times New Roman');

title(ax1, ...
    '五级目标的求解状态与相对差距', ...
    'FontName', 'SimSun', ...
    'FontSize', 13);

ax1.FontName = 'Times New Roman';
ax1.FontSize = 11;
ax1.YDir = 'reverse';

grid(ax1, 'on');
box(ax1, 'on');

gapMax = max(gap(1:4), [], 'omitnan');
xlim(ax1, [0 max(10.8, gapMax * 1.25)]);

%% 认证状态
text(ax1, 0.98, 0.94, ...
    'All stages: FEASIBLE', ...
    'Units', 'normalized', ...
    'HorizontalAlignment', 'right', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10);

text(ax1, 0.98, 0.86, ...
    'Stages 2-5 conditioned on uncertified parent', ...
    'Units', 'normalized', ...
    'HorizontalAlignment', 'right', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 9);

text(ax1, 0.98, 0.78, ...
    'Full lexicographic certified: NO', ...
    'Units', 'normalized', ...
    'HorizontalAlignment', 'right', ...
    'FontName', 'Times New Roman', ...
    'FontSize', 10);

%% (b) 各阶段求解时间
ax2 = nexttile;

plot(ax2, ...
    1:n, time, '-o', ...
    'LineWidth', 1.7, ...
    'MarkerSize', 7, ...
    'MarkerFaceColor', 'w');

xticks(ax2, 1:n);
xticklabels(ax2, stageNames);

ylabel(ax2, ...
    'Solver time / s', ...
    'FontName', 'Times New Roman');

title(ax2, ...
    '五级词典序各阶段实际求解时间', ...
    'FontName', 'SimSun', ...
    'FontSize', 13);

ax2.FontName = 'Times New Roman';
ax2.FontSize = 11;

grid(ax2, 'on');
box(ax2, 'on');

for i = 1:n

    text(ax2, i, time(i), ...
        sprintf('%.0f', time(i)), ...
        'HorizontalAlignment', 'center', ...
        'VerticalAlignment', 'bottom', ...
        'FontName', 'Times New Roman', ...
        'FontSize', 10);
end

ylim(ax2, [0 max(time) * 1.18]);


function root = projectRoot()

p = fileparts(mfilename('fullpath'));

for k = 1:8

    if isfile(fullfile(p, '代码', 'q1', ...
            'outputs', 'q1-summary.json'))

        root = p;
        return;
    end

    parent = fileparts(p);

    if strcmp(parent, p)
        break;
    end

    p = parent;
end

error('无法自动定位 CLB_B 仓库根目录。');

end